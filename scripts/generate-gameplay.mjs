import { readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const dir = fileURLToPath(new URL('../shared/gameplay/', import.meta.url));
const out = fileURLToPath(new URL('../src/generated-gameplay.ts', import.meta.url));

const ORDER = [
  'math.ts',
  'types.ts',
  'ids.ts',
  'ballistics.ts',
  'stance.ts',
  'spread.ts',
  'recoil.ts',
  'collide.ts',
  'movement.ts',
  'controller.ts',
  'reload.ts',
  'fire.ts',
  'melee.ts',
  'ai.ts',
  'throwables.ts',
  'loot.ts',
  'crosshair.ts',
  'combat-fx.ts',
  'death.ts',
  'hurt-feedback.ts',
  'attachments.ts',
  'nameplate.ts',
  'stealth.ts',
  'mission-director.ts',
];

const present = new Set(await readdir(dir));
for (const file of ORDER) {
  if (!present.has(file)) throw new Error(`missing shared/gameplay/${file}`);
}

const exported = [];
let body = '';
for (const file of ORDER) {
  let text = await readFile(join(dir, file), 'utf8');
  for (const match of text.matchAll(/^export (?:async )?function ([A-Za-z0-9_]+)/gm))
    exported.push(match[1]);
  for (const match of text.matchAll(/^export const ([A-Za-z0-9_]+)/gm)) exported.push(match[1]);
  text = text.replace(/import\s+(?:type\s+)?(?:[\s\S]*?)\s+from\s+['"][^'"]+['"];?\r?\n/g, '');
  text = text.replace(/^export /gm, '');
  body += `\n/* ==== shared/gameplay/${file} ==== */\n${text}\n`;
}

const unique = [...new Set(exported)];
const generated = `// GENERATED by scripts/generate-gameplay.mjs from shared/gameplay — do not edit.
'use strict';
const Gameplay = (() => {
${body}
  return {
${unique.map((name) => `    ${name},`).join('\n')}
  };
})();
`;

await writeFile(out, generated);
console.log(`wrote ${out} (${unique.length} exports)`);
