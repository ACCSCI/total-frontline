/* build all viewmodels once, keep them parented under the animation rig */
const vmRoot = new THREE.Group(); // camera-space anchor
const vmSway = new THREE.Group(); // sway + bob + pose
const vmRecoil = new THREE.Group(); // recoil spring
vmScene.add(vmRoot);
vmRoot.add(vmSway);
vmSway.add(vmRecoil);

/* the models were laid out at 1:1 scale; shrinking them here frees the centre
   of the screen without re-tuning every part offset. ADS poses are stated in
   model space, so they scale with it. */
const VM_SCALE = 0.86;

WEAPONS.forEach((w) => {
  const vm = w.build();
  w.vm = vm;
  texelize(vm.group, GUN_PER_M);
  vm.group.visible = false;
  vm.group.scale.setScalar(VM_SCALE);
  vm.adsPos.x *= VM_SCALE;
  vm.adsPos.y *= VM_SCALE;
  vmRecoil.add(vm.group);
  w.mag = w.magSize;
  w.res = w.reserve;
  w.semi = false;
  w.spread = w.spreadBase;
});

